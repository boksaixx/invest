// 장 시간대·휴장일 판정 회귀 테스트 — 휴장일에 "장중"으로 판정하면 크론이 API 비용을 태우고
// 화면은 존재하지 않는 장을 분석한다.
//
// 실행: npx tsx scripts/validate-market-phase.ts
//
// 2026-09 감사에서 확인: 양력 고정일만 있어 설날·추석 연휴에 "장중"으로 판정했다.
import { getMarketPhase, getUSMarketPhase } from "../lib/marketPhase";

let fail = 0;
const ok = (c: boolean, m: string) => {
  if (!c) fail++;
  console.log(`${c ? "✅" : "❌"} ${m}`);
};
/** KST 시각을 UTC Date로 */
const kst = (ymd: string, hhmm: string) => new Date(`${ymd}T${hhmm}:00+09:00`);

console.log("=== KRX ===");
const cases: [string, string, string][] = [
  ["2026-09-24", "10:00", "휴장(공휴일)"], // 추석 연휴
  ["2026-09-25", "10:00", "휴장(공휴일)"], // 추석
  ["2026-09-28", "10:00", "장중"], // 추석 다음 월요일
  ["2026-02-17", "10:00", "휴장(공휴일)"], // 설날
  ["2026-03-02", "10:00", "휴장(공휴일)"], // 삼일절 대체
  ["2026-05-01", "10:00", "휴장(공휴일)"], // 근로자의날
  ["2026-06-03", "10:00", "휴장(공휴일)"], // 지방선거
  ["2026-12-31", "10:00", "휴장(공휴일)"], // 연말 폐장
  ["2026-09-07", "08:30", "장전"],
  ["2026-09-07", "09:10", "장초반"],
  ["2026-09-07", "10:00", "장중"],
  ["2026-09-07", "12:00", "점심시간대"],
  ["2026-09-07", "14:50", "마감임박"],
  ["2026-09-07", "15:25", "동시호가"],
  ["2026-09-07", "16:00", "장마감"],
  ["2026-09-05", "10:00", "휴장(주말)"], // 토
  ["2026-09-06", "20:00", "휴장(주말)"], // 일 (주간 크론)
  ["2027-09-15", "10:00", "휴장(공휴일)"], // 2027 추석
  ["2028-12-25", "10:00", "휴장(공휴일)"], // 표 없는 연도(월요일) → 양력 고정일 폴백
  ["2028-03-01", "10:00", "휴장(공휴일)"],
  ["2028-01-01", "10:00", "휴장(주말)"], // 2028-01-01은 토요일 — 주말이 먼저
];
for (const [d, t, expect] of cases) {
  const p = getMarketPhase(kst(d, t));
  ok(p.phase === expect, `${d} ${t} KST → ${p.phase} (기대 ${expect})`);
}

console.log("\n=== 미국(NYSE) ===");
const us: [string, string][] = [
  ["2026-11-26T15:00:00Z", "휴장(공휴일)"], // 추수감사절 (ET 10:00)
  ["2026-07-03T15:00:00Z", "휴장(공휴일)"], // 독립기념일 관측일
  ["2026-09-07T15:00:00Z", "휴장(공휴일)"], // 노동절
  ["2026-09-08T13:45:00Z", "장초반"], // ET 09:45 (EDT) — 개장 후 30분 안
  ["2026-09-08T14:00:00Z", "장중"], // ET 10:00 (EDT) — 장초반 끝
  ["2026-09-08T16:30:00Z", "점심시간대"], // ET 12:30 (EDT)
  ["2026-12-15T16:30:00Z", "장중"], // EST: ET 11:30 → 장중 (서머타임 해제 반영)
  ["2026-12-25T15:00:00Z", "휴장(공휴일)"],
];
for (const [iso, expect] of us) {
  const p = getUSMarketPhase(new Date(iso));
  ok(p.phase === expect, `${iso} → ${p.phase} (기대 ${expect})`);
}

console.log(fail === 0 ? "\n전체 통과" : `\n실패 ${fail}건`);
process.exit(fail === 0 ? 0 : 1);
